import { useEffect, useLayoutEffect, useMemo, useRef, useState } from 'react';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import { ArrowDown, Copy, Check, Volume2, FileText, Clock3, Square, Download } from 'lucide-react';
import { authHeaders } from '../api';
import { speechLanguage } from '../speech';
import type { Chat, Lang } from '../types';
import { IconButton, TrisMark } from './ui';

function GeneratedMedia({ href, lang, loaded }: { href: string; lang: Lang; loaded: () => void }) {
  const [url, setUrl] = useState('');
  const [error, setError] = useState('');
  useEffect(() => {
    const controller = new AbortController();
    let blobUrl = '';
    fetch(href, { headers: authHeaders(), signal: controller.signal })
      .then(async (response) => {
        if (!response.ok)
          throw new Error(
            lang === 'vi'
              ? 'Đăng nhập lại để xem tệp đã tạo.'
              : 'Sign in again to view this media.',
          );
        blobUrl = URL.createObjectURL(await response.blob());
        if (controller.signal.aborted) URL.revokeObjectURL(blobUrl);
        else setUrl(blobUrl);
      })
      .catch((e) => {
        if (!controller.signal.aborted) setError(e.message);
      });
    return () => {
      controller.abort();
      if (blobUrl) URL.revokeObjectURL(blobUrl);
    };
  }, [href, lang]);
  if (error) return <span role="alert">{error}</span>;
  if (!url) return <span role="status">{lang === 'vi' ? 'Đang tải ảnh…' : 'Loading media…'}</span>;
  return (
    <span className="chat-generated-media">
      {href.endsWith('.mp4') ? (
        <video src={url} controls preload="metadata" onLoadedMetadata={loaded} />
      ) : (
        <img
          src={url}
          alt={lang === 'vi' ? 'Ảnh do Tris tạo' : 'Generated by Tris'}
          onLoad={loaded}
        />
      )}
      <a href={url} download={href.split('/').pop()}>
        <Download size={15} />
        {lang === 'vi' ? 'Tải xuống' : 'Download'}
      </a>
    </span>
  );
}

function CodeBlock({ children, ...props }: React.ComponentProps<'pre'>) {
  const ref = useRef<HTMLPreElement>(null);
  const [copied, setCopied] = useState(false);
  return (
    <div className="code-block">
      <div className="code-header">
        <span>Code</span>
        <button
          onClick={async () => {
            try {
              await navigator.clipboard.writeText(ref.current?.innerText || '');
              setCopied(true);
              setTimeout(() => setCopied(false), 1600);
            } catch {
              setCopied(false);
            }
          }}
          aria-label="Sao chép mã / Copy code"
        >
          {copied ? <Check size={13} /> : <Copy size={13} />}
          {copied ? 'Copied' : 'Copy'}
        </button>
      </div>
      <pre ref={ref} {...props}>
        {children}
      </pre>
    </div>
  );
}

export type QuickAction = { label: string; run: () => void };

function CompareView({ compare, lang }: { compare: NonNullable<Chat['messages'][number]['compare']>; lang: Lang }) {
  const t = (vi: string, en: string) => (lang === 'vi' ? vi : en);
  return (
    <div className="compare-block" data-testid="compare-block">
      <div className="compare-grid">
        <section className="compare-col">
          <header>{compare.modelA}</header>
          <div className="markdown">
            <ReactMarkdown remarkPlugins={[remarkGfm]}>{compare.a || '…'}</ReactMarkdown>
          </div>
        </section>
        <section className="compare-col">
          <header>{compare.modelB}</header>
          <div className="markdown">
            <ReactMarkdown remarkPlugins={[remarkGfm]}>{compare.b || '…'}</ReactMarkdown>
          </div>
        </section>
      </div>
      {(compare.judge || compare.a || compare.b) && (
        <section className="compare-judge">
          <header>{t('Kết luận đối chiếu', 'Cross-check verdict')}</header>
          {compare.judge ? (
            <div className="markdown">
              <ReactMarkdown remarkPlugins={[remarkGfm]}>{compare.judge}</ReactMarkdown>
            </div>
          ) : (
            <div className="thinking-placeholder" role="status">
              <span />
              <span />
              <span />
            </div>
          )}
        </section>
      )}
    </div>
  );
}

export function ChatScrollArea({
  chat,
  busy,
  lang,
  notify,
  quickReplies,
  completionActions,
}: {
  chat: Chat;
  busy: boolean;
  lang: Lang;
  notify: (text: string) => void;
  quickReplies?: QuickAction[];
  completionActions?: QuickAction[];
}) {
  const scroll = useRef<HTMLDivElement>(null);
  const follow = useRef(true);
  const [jump, setJump] = useState(false);
  const [playing, setPlaying] = useState<string | null>(null);
  const audio = useRef<HTMLAudioElement | null>(null);
  const speechRequest = useRef<AbortController | null>(null);
  const t = (vi: string, en: string) => (lang === 'vi' ? vi : en);
  const latest = chat.messages.at(-1)?.content;
  // Stable component identity prevents media re-downloads during resize/streaming.
  const markdownComponents = useMemo(
    () => ({
      pre: CodeBlock,
      a: ({ children, ...props }: React.ComponentProps<'a'>) =>
        props.href && /^\/v1\/media\/tris_[a-zA-Z0-9_.-]+\.(png|gif|mp4)$/.test(props.href) ? (
          <GeneratedMedia
            href={props.href}
            lang={lang}
            loaded={() => {
              if (follow.current && scroll.current)
                scroll.current.scrollTop = scroll.current.scrollHeight;
            }}
          />
        ) : (
          <a {...props} target="_blank" rel="noopener noreferrer">
            {children}
          </a>
        ),
    }),
    [lang],
  );
  useLayoutEffect(() => {
    follow.current = true;
    setJump(false);
    if (scroll.current) scroll.current.scrollTop = scroll.current.scrollHeight;
  }, [chat.id]);
  useLayoutEffect(() => {
    if (follow.current && scroll.current) scroll.current.scrollTop = scroll.current.scrollHeight;
    else if (busy) setJump(true);
  }, [latest, chat.messages.length, busy]);
  useEffect(
    () => () => {
      speechRequest.current?.abort();
      audio.current?.pause();
      if (audio.current?.src) URL.revokeObjectURL(audio.current.src);
    },
    [chat.id],
  );
  async function speak(id: string, text: string) {
    if (playing === id) {
      speechRequest.current?.abort();
      audio.current?.pause();
      setPlaying(null);
      return;
    }
    if (chat.demo) {
      notify(
        t(
          'Giọng nói dùng với phản hồi AI local thật.',
          'Voice playback is available for local AI responses.',
        ),
      );
      return;
    }
    speechRequest.current?.abort();
    const speech = new AbortController();
    speechRequest.current = speech;
    try {
      audio.current?.pause();
      if (audio.current?.src) URL.revokeObjectURL(audio.current.src);
      setPlaying(id);
      const r = await fetch('/v1/speech', {
        method: 'POST',
        signal: speech.signal,
        headers: { 'Content-Type': 'application/json', ...authHeaders() },
        body: JSON.stringify({
          text: text.slice(0, 800),
          language: speechLanguage(text),
        }),
      });
      if (!r.ok) {
        const details = await r.json().catch(() => ({}));
        throw new Error(
          details.detail || 'Giọng mẫu chưa sẵn sàng. Không tự thay bằng giọng khác.',
        );
      }
      const blob = await r.blob();
      if (speech.signal.aborted) return;
      const player = new Audio(URL.createObjectURL(blob));
      audio.current = player;
      player.onended = () => setPlaying(null);
      await player.play();
    } catch (error) {
      if (!speech.signal.aborted) {
        setPlaying(null);
        notify(
          error instanceof Error
            ? error.message
            : t(
                'Chưa phát được giọng nói. Hãy kiểm tra dịch vụ TTS.',
                'Speech is unavailable. Check the TTS service.',
              ),
        );
      }
    }
  }
  return (
    <div className="chat-scroll-wrap" data-busy={busy ? 'true' : 'false'}>
      <div
        ref={scroll}
        className="chat-scroll"
        data-testid="chat-scroll"
        role="log"
        aria-label={t('Tin nhắn', 'Messages')}
        aria-live={busy ? 'off' : 'polite'}
        onScroll={() => {
          const el = scroll.current!;
          const near = el.scrollHeight - el.scrollTop - el.clientHeight < 80;
          follow.current = near;
          setJump(!near);
        }}
      >
        <div className="message-column">
          {chat.demo && (
            <div className="sample-note">
              {t(
                'Hội thoại mẫu · dùng để trải nghiệm giao diện',
                'Sample conversation · for exploring the interface',
              )}
            </div>
          )}
          {chat.messages.map((m, i) => (
            <article key={m.id} className={`message ${m.role} ${m.error ? 'message-error' : ''}`}>
              {m.role === 'assistant' && (
                <div className="assistant-label">
                  <TrisMark />
                  <strong>Tris</strong>
                  {busy && i === chat.messages.length - 1 && (
                    <span className="thinking-label">
                      {m.queued
                        ? t('Đang xếp hàng', 'Queued')
                        : m.compare
                          ? t('Đang đối chiếu', 'Cross-checking')
                          : t('Đang trả lời', 'Responding')}
                      <span className="thinking-dots">···</span>
                    </span>
                  )}
                </div>
              )}
              {!!m.attachments?.length && (
                <div className="message-files">
                  {m.attachments.map((a) => (
                    <div key={a.id} className="file-chip">
                      <FileText size={18} />
                      <span>
                        {a.name}
                        <small>{(a.size / 1024 / 1024).toFixed(1)} MB</small>
                      </span>
                    </div>
                  ))}
                </div>
              )}
              {m.compare ? (
                <>
                  {m.status && <small className="compare-status">{m.status}</small>}
                  <CompareView compare={m.compare} lang={lang} />
                </>
              ) : m.content ? (
                <div className="markdown">
                  <ReactMarkdown remarkPlugins={[remarkGfm]} components={markdownComponents}>
                    {m.content}
                  </ReactMarkdown>
                </div>
              ) : (
                <div className="thinking-placeholder" role="status">
                  {m.queued && <span className="queued-pill">{t('Đang chờ lượt', 'Waiting')}</span>}
                  {m.status && <small aria-live="polite">{m.status}</small>}
                  <span />
                  <span />
                  <span />
                </div>
              )}
              {m.role === 'assistant' && m.content && !(busy && i === chat.messages.length - 1) && (
                <div className="message-meta">
                  <IconButton
                    label={t('Sao chép', 'Copy')}
                    onClick={async () => {
                      try {
                        await navigator.clipboard.writeText(m.content);
                        notify(t('Đã sao chép', 'Copied'));
                      } catch {
                        notify(
                          t(
                            'Trình duyệt không cho phép sao chép.',
                            'Clipboard access is unavailable.',
                          ),
                        );
                      }
                    }}
                  >
                    <Copy size={15} />
                  </IconButton>
                  <IconButton
                    label={
                      playing === m.id
                        ? t('Dừng phát', 'Stop playback')
                        : t('Đọc câu trả lời', 'Read aloud')
                    }
                    className={`speaker ${playing === m.id ? 'playing' : ''}`}
                    onClick={() => speak(m.id, m.content)}
                  >
                    {playing === m.id ? <Square size={14} /> : <Volume2 size={17} />}
                  </IconButton>
                  {m.seconds !== undefined && (
                    <span className="processing-time">
                      <Clock3 size={12} />
                      {t(
                        `Đã xử lý trong ${Math.floor(m.seconds / 60)} phút ${m.seconds % 60} giây`,
                        `Processed in ${Math.floor(m.seconds / 60)}m ${m.seconds % 60}s`,
                      )}
                    </span>
                  )}
                </div>
              )}
              {!!m.sources?.length && (
                <div className="source-list">
                  {m.sources.map((s) =>
                    s.url ? (
                      <a key={s.label} href={s.url} target="_blank" rel="noopener noreferrer">
                        {s.label} · {s.title}
                      </a>
                    ) : (
                      <span key={s.label}>
                        {s.label} · {s.title}
                      </span>
                    ),
                  )}
                </div>
              )}
              {m.role === 'assistant' && i === chat.messages.length - 1 && completionActions?.length && (
                <div
                  className="quick-replies completion"
                  role="group"
                  aria-label={t('Hành động với kết quả này', 'Actions for this result')}
                >
                  {completionActions.map((action) => (
                    <button key={action.label} type="button" className="quick-reply" onClick={action.run}>
                      {action.label}
                    </button>
                  ))}
                </div>
              )}
            </article>
          ))}
          {busy && !!quickReplies?.length && (
            <div
              className="quick-replies"
              role="group"
              aria-label={t('Gợi ý nhanh trong lúc chờ', 'Quick replies while waiting')}
            >
              {quickReplies.map((action) => (
                <button key={action.label} type="button" className="quick-reply" onClick={action.run}>
                  {action.label}
                </button>
              ))}
            </div>
          )}
        </div>
      </div>
      {jump && (
        <button
          className="jump-button"
          onClick={() => {
            follow.current = true;
            setJump(false);
            scroll.current?.scrollTo({
              top: scroll.current.scrollHeight,
              behavior: matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth',
            });
          }}
          aria-label={t('Về tin nhắn mới nhất', 'Jump to latest message')}
        >
          <ArrowDown size={16} />
          <span>{t('Tin nhắn mới nhất', 'Latest message')}</span>
        </button>
      )}
    </div>
  );
}
